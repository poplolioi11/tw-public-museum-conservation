#!/usr/bin/env python3
"""Render bounded review-cell proportions and multilabel note counts offline.

Optional plotting dependency: requirements-figures.txt.  The default inputs are
the canonical facts, inventory, dimensions and public annotation vocabulary.
Coverage is regenerated by coverage.generate; --coverage may assert an expected
coverage JSON.  No conservation quantity is read, summed, converted or ranked.
SVG embeds font outlines for portability. --font-file selects a CJK font when
automatic discovery cannot find one. --preview-dir writes optional PNG previews.
"""
import argparse
from collections import Counter
import hashlib
import io
import json
from pathlib import Path
import re

import coverage as coverage_model
from enrichment import figure_source_sha

ROOT = Path(__file__).resolve().parents[1]
STATE_ORDER = tuple(coverage_model.STATES)
STATE_LABELS = {
    "numeric_only": "只有已核數值查核",
    "no_quantity_scope_only": "只有指定段未定位適用量",
    "mixed_current_states": "同格有不同來源狀態",
    "source_not_located": "本輪未定位來源",
    "body_pending": "適用正文待核",
    "annual_not_separable": "年度範圍不可分離",
    "outside_scope": "不在採用範圍",
    "not_assessed": "本版無館年查核索引",
}
COLORS = ("#296783", "#B7D4CD", "#705A83", "#CDA065",
          "#89ADC2", "#BA8E93", "#AEA89C", "#E7E7E2")
HATCHES = ("", "", "xx", "//", "..", "\\\\", "++", "oo")
INK = "#26343C"
POPULATION_LABELS = {
    "baseline_inventory_71x6": "原 71 組織 × 六年歷史索引格",
    "reviewed_cohort": "本版已有有界查核的館年格",
    "baseline_review_union": "歷史索引與本版查核的聯集",
}


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def require(condition, message):
    if not condition:
        raise ValueError(message)


def validate_plot_data(coverage, annotations, vocabulary):
    """Assert actual cell denominators; never explode batch membership sets."""
    require(tuple(coverage["state_labels"]) == STATE_ORDER or
            set(coverage["state_labels"]) == set(STATE_ORDER), "coverage state vocabulary changed")
    cells = coverage["cells"]
    require(len({r["coverage_cell_id"] for r in cells}) == len(cells), "duplicate coverage cells")
    for population in coverage["populations"]:
        selected = [r for r in cells if population["population_id"] in r["populations"]]
        counts = Counter(r["coverage_state"] for r in selected)
        require(population["denominator_cells"] == len(selected), "population denominator mismatch")
        require(all(counts[s] == population["state_counts"][s] for s in STATE_ORDER),
                "population state-count mismatch")
    reviewed = [r for r in cells if "reviewed_cohort" in r["populations"]]
    for axis in ("year", "working_category_by_batch", "admin_group", "island_group"):
        groups = [g for g in coverage["groups"]
                  if g["population_id"] == "reviewed_cohort" and g["dimension"] == axis]
        require(sum(g["denominator_cells"] for g in groups) == len(reviewed),
                "facet groups are not a disjoint partition: " + axis)
        for group in groups:
            require(group["all_memberships_preserved_as_one_disjoint_set"] is True,
                    "batch memberships were exploded")
            field = {"year": "target_data_year", "working_category_by_batch":
                     "working_category_membership_set"}.get(axis, axis)
            value = next(iter(group["group_values"].values()))
            selected = [r for r in reviewed if r[field] == value]
            counts = Counter(r["coverage_state"] for r in selected)
            require(len(selected) == group["denominator_cells"], "facet denominator mismatch")
            require(all(counts[s] == group["state_counts"][s] for s in STATE_ORDER),
                    "facet state-count mismatch")
    require(len(annotations) == len({r["review_id"] for r in annotations}), "duplicate note annotations")
    review_ids = {rid for row in cells for rid in row["review_ids"]}
    for row in annotations:
        require(row["review_id"] in review_ids, "annotation not linked to a current review")
        require(len(row["content_tags"]) == len(set(row["content_tags"])), "duplicate tag within note")
        require(set(row["content_tags"]) <= set(vocabulary["content_tag_labels"]), "unknown content tag")
        require(row["classification_status"] in ("supported_by_review_note", "insufficient_detail"),
                "unknown annotation classification status")
        if row["classification_status"] == "insufficient_detail":
            require(not row["content_tags"], "insufficient notes must not have assigned content tags")
    return len(reviewed)


def _font_path(explicit, all_text):
    from matplotlib import font_manager, ft2font
    if explicit:
        candidates = [Path(explicit)]
    else:
        candidates = []
        for family in ("Heiti TC", "PingFang TC", "Noto Sans CJK TC", "Noto Sans TC",
                       "Source Han Sans TW", "Microsoft JhengHei", "WenQuanYi Zen Hei"):
            try:
                path = Path(font_manager.findfont(family, fallback_to_default=False))
                if path not in candidates:
                    candidates.append(path)
            except ValueError:
                pass
    needed = {ord(char) for char in all_text if not char.isspace()}
    for path in candidates:
        if path.is_file() and needed <= set(ft2font.FT2Font(str(path)).get_charmap()):
            return path
    raise ValueError("No complete CJK font found; pass --font-file with a Traditional Chinese font")


def _batch_label(value):
    aliases = {"NPM": "NPM 批次", "BATCH2": "順序二", "BATCH3": "順序三",
               "BATCH4": "順序四", "BATCH5": "順序五", "BATCH6": "順序六",
               "pre_batch_or_unassigned": "前批次或未指派"}
    return " ＋ ".join(aliases.get(part, part) for part in value.split("+"))


def _group_label(axis, group):
    value = next(iter(group["group_values"].values()))
    if axis == "year":
        return str(value)
    if axis == "working_category_by_batch":
        return _batch_label(value)
    if axis == "admin_group":
        return {"central": "中央", "local": "地方", "unknown": "未知（unknown）"}[value]
    return {"main_island": "本島", "offshore": "離島", "unknown": "未知（unknown）"}[value]


def _axes_style(ax):
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.spines["bottom"].set_color("#AAB3B7")
    ax.tick_params(axis="y", length=0, pad=9, colors=INK)
    ax.tick_params(axis="x", colors=INK, length=3)
    ax.set_axisbelow(True)
    ax.grid(axis="x", color="#DCE2E4", linewidth=0.6)
    ax.set_xlim(0, 100)
    ax.set_xticks([0, 25, 50, 75, 100], ["0%", "25%", "50%", "75%", "100%"])


def _stacked(ax, groups, labels, threshold=9):
    for y, (group, label) in enumerate(zip(groups, labels)):
        n = group["denominator_cells"]
        require(n > 0 and sum(group["state_counts"].values()) == n, "invalid stack denominator")
        left = 0.0
        for i, state in enumerate(STATE_ORDER):
            count = group["state_counts"][state]
            width = count / n * 100
            if count:
                ax.barh(y, width, left=left, height=0.60, color=COLORS[i],
                        edgecolor=INK, linewidth=0.45, hatch=HATCHES[i], zorder=3)
                if width >= threshold:
                    ax.text(left + width / 2, y, f"{width:.1f}%", ha="center", va="center",
                            color="white" if i in (0, 2) else INK, fontsize=9.5, zorder=4,
                            bbox=dict(facecolor=COLORS[i], edgecolor="none", pad=.7)
                            if HATCHES[i] else None)
            left += width
        require(abs(left - 100) < 1e-8, "stack does not total 100 percent")
    ax.set_yticks(range(len(groups)), [f"{label}  (n={g['denominator_cells']})"
                                     for label, g in zip(labels, groups)])
    ax.set_ylim(len(groups) - .45, -.55)
    _axes_style(ax)


def _legend(fig, y, columns=4):
    from matplotlib.patches import Patch
    handles = [Patch(facecolor=COLORS[i], edgecolor=INK, linewidth=.5,
                     hatch=HATCHES[i], label=STATE_LABELS[state])
               for i, state in enumerate(STATE_ORDER)]
    # Matplotlib fills columns; arrange handles for a left-to-right row order.
    handles = [handles[i] for i in (0, 4, 1, 5, 2, 6, 3, 7)]
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(.52, y),
               ncol=columns, frameon=False, fontsize=10, columnspacing=1.5,
               handlelength=1.9, handleheight=1.15, labelspacing=1.1)


def _header(fig, title, subtitle):
    fig.text(.04, .965, title, ha="left", va="top", fontsize=19, color=INK)
    fig.text(.04, .905, subtitle, ha="left", va="top", fontsize=11, color=INK)


def _coverage_states(coverage):
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(14, 5.9))
    fig.subplots_adjust(left=.335, right=.965, top=.62, bottom=.24)
    _header(fig, "三種有界集合的查核格狀態", "觀察單位：候選識別 × 目標年格；每列以自身 n 為 100%。")
    _legend(fig, .82)
    groups = coverage["populations"]
    _stacked(ax, groups, [POPULATION_LABELS[g["population_id"]] for g in groups], threshold=8)
    ax.set_xlabel("館年格比例（非全國公開率）", labelpad=12)
    fig.text(.04, .12, "同格不同來源狀態保留為混合；本版無查核與本輪未定位來源分開。", fontsize=10.5, color=INK)
    fig.text(.04, .065, "柱形只描述本版查核範圍，不代表全年保存修護量、機構績效或完整年度作業。", fontsize=10.5, color=INK)
    return fig


def _coverage_facets(coverage):
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(2, 2, figsize=(17.5, 11.8))
    fig.subplots_adjust(left=.145, right=.97, top=.74, bottom=.17, wspace=.62, hspace=.48)
    reviewed = next(p for p in coverage["populations"] if p["population_id"] == "reviewed_cohort")
    _header(fig, "已有有界查核館年格的四個切面", f"只取 reviewed_cohort：n={reviewed['denominator_cells']} 館年格；每個分組以自身 n 為 100%。")
    _legend(fig, .84)
    definitions = [("year", "A  目標年度"),
                   ("working_category_by_batch", "B  工作批次完整成員集合"),
                   ("admin_group", "C  原權管文字的行政群組"),
                   ("island_group", "D  原中繼資料的島群")]
    for ax, (axis, title) in zip(axes.flat, definitions):
        groups = [g for g in coverage["groups"]
                  if g["population_id"] == "reviewed_cohort" and g["dimension"] == axis]
        # Original value order is used, not a count/rate ranking.
        groups.sort(key=lambda g: str(next(iter(g["group_values"].values()))))
        labels = [_group_label(axis, group) for group in groups]
        _stacked(ax, groups, labels, threshold=12)
        ax.set_title(title, loc="left", fontsize=13, pad=14, color=INK)
        ax.set_xlabel("館年格比例", labelpad=8)
        for tick, label in zip(ax.get_yticklabels(), labels):
            if "unknown" in label:
                tick.set_color("#8F3F36")
                tick.set_bbox(dict(facecolor="#FFF0DB", edgecolor="#8F3F36", pad=2.5, linewidth=.6))
    fig.text(.04, .095, "未知（unknown）保留獨立分母；工作批次是整理流程，不是官方館類。多批次以完整集合互斥分組，不拆批重算。", fontsize=10.5, color=INK)
    fig.text(.04, .055, "每年納入集合可能不同；原名錄 PDF 的未覆核層級保留，行政與島群不推及所有分館、實物或藏品所有權。", fontsize=10.5, color=INK)
    return fig


def _absence_tags(annotations, vocabulary):
    import matplotlib.pyplot as plt
    labels = vocabulary["content_tag_labels"]
    counts = Counter(tag for row in annotations for tag in row["content_tags"])
    statuses = Counter(row["classification_status"] for row in annotations)
    fig, ax = plt.subplots(figsize=(13.5, 8.2))
    fig.subplots_adjust(left=.31, right=.94, top=.77, bottom=.20)
    _header(fig, "指定段未定位適用量：既有說明中的內容標籤", f"n={len(annotations)} 則目前 N 查核註記；標籤可複選，依詞表原順序呈現，沒有排名。")
    keys = list(labels)
    values = [counts[key] for key in keys]
    ax.barh(range(len(keys)), values, height=.62, color="#4E7D82", edgecolor=INK, linewidth=.5)
    ax.set_yticks(range(len(keys)), [labels[key] for key in keys])
    ax.set_ylim(len(keys)-.45, -.55)
    ax.set_xlim(0, max(values + [1]) * 1.18)
    for y, count in enumerate(values):
        ax.text(count + max(values + [1]) * .018, y, str(count), va="center", ha="left", color=INK, fontsize=11)
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.spines["bottom"].set_color("#AAB3B7")
    ax.tick_params(axis="y", length=0, pad=9, colors=INK)
    ax.tick_params(axis="x", colors=INK)
    ax.set_axisbelow(True)
    ax.grid(axis="x", color="#DCE2E4", linewidth=.6)
    ax.set_xlabel("具有該標籤的查核註記數（可重疊）", labelpad=12)
    fig.text(.04, .13, f"既有說明文字支持：{statuses['supported_by_review_note']} 則；資訊不足：{statuses['insufficient_detail']} 則。資訊不足者不強派內容標籤。", fontsize=10.5, color=INK)
    fig.text(.04, .08, "各列不可相加成館年、機構、報告或物件總數；沒有標籤不代表已證明該內容不存在。", fontsize=10.5, color=INK)
    fig.text(.04, .04, "標籤只描述既有公開查核說明的指定範圍，不是機構未做或未公開的原因調查。", fontsize=10.5, color=INK)
    return fig


def generate_figures(coverage, annotations, vocabulary, font_file=None, preview_dir=None):
    """Return {figure name: SVG bytes}; optionally save local-only PNG previews."""
    import matplotlib
    matplotlib.use("Agg", force=True)
    import matplotlib.pyplot as plt
    from matplotlib import font_manager
    validate_plot_data(coverage, annotations, vocabulary)
    # Validate the glyphs actually used by this script, including source labels.
    text = Path(__file__).read_text(encoding="utf-8") + "".join(vocabulary["content_tag_labels"].values())
    font_path = _font_path(font_file, text)
    font_manager.fontManager.addfont(str(font_path))
    font_name = font_manager.FontProperties(fname=str(font_path)).get_name()
    styles = {"font.family": font_name, "font.size": 10.5, "axes.unicode_minus": False,
              "text.color": INK, "axes.labelcolor": INK, "figure.facecolor": "white",
              "axes.facecolor": "white", "savefig.facecolor": "white",
              "svg.fonttype": "path", "svg.hashsalt": "museum-coverage-figures-1.0",
              "hatch.linewidth": .45}
    source_sha = figure_source_sha(coverage, annotations, vocabulary)
    outputs = {}
    with plt.rc_context(styles):
        figures = {"coverage-states.svg": _coverage_states(coverage),
                   "coverage-facets.svg": _coverage_facets(coverage),
                   "absence-tags.svg": _absence_tags(annotations, vocabulary)}
        for name, fig in figures.items():
            stream = io.BytesIO()
            fig.savefig(stream, format="svg", metadata={"Date": None, "Creator": "Matplotlib",
                        "Description": "有界查核格與既有說明標籤；非全國估計，不含保存修護量加總。"})
            body = b"\n".join(line.rstrip() for line in stream.getvalue().splitlines()) + b"\n"
            marker = f"<!-- enrichment-source-sha256: {source_sha} -->\n".encode()
            # Preserve XML declaration/DOCTYPE and add provenance within the root.
            match = re.search(rb"<svg\b[^>]*>", body)
            require(match is not None, "invalid SVG root")
            body = body[:match.end()] + b"\n" + marker + body[match.end():]
            require(b"<script" not in body and (b"/" + b"Users/") not in body, "unsafe SVG content")
            outputs[name] = body
            if preview_dir is not None:
                preview_dir = Path(preview_dir)
                preview_dir.mkdir(parents=True, exist_ok=True)
                fig.savefig(preview_dir / (Path(name).stem + ".png"), dpi=160, format="png",
                            metadata={"Software": "Matplotlib"})
            plt.close(fig)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--facts", type=Path, default=ROOT / "data/facts.json")
    parser.add_argument("--coverage", type=Path, help="assert regenerated coverage equals this JSON")
    parser.add_argument("--inventory", type=Path, default=ROOT / "metadata/inventory.json")
    parser.add_argument("--dimensions", type=Path, default=ROOT / "metadata/organization_dimensions.json")
    parser.add_argument("--annotations", type=Path, default=ROOT / "data/absence_annotations.json")
    parser.add_argument("--vocabulary", type=Path, default=ROOT / "metadata/absence_vocabulary.json")
    parser.add_argument("--font-file", type=Path)
    parser.add_argument("--preview-dir", type=Path)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "docs/figures")
    parser.add_argument("--check", action="store_true", help="compare SVG bytes instead of writing")
    args = parser.parse_args()
    facts, inventory, dimensions = read(args.facts), read(args.inventory), read(args.dimensions)
    coverage = coverage_model.generate(facts, inventory, dimensions)
    if args.coverage:
        require(coverage == read(args.coverage), "candidate coverage differs from regenerated coverage")
    annotations, vocabulary = read(args.annotations), read(args.vocabulary)
    outputs = generate_figures(coverage, annotations, vocabulary, args.font_file, args.preview_dir)
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, body in outputs.items():
        path = args.output_dir / name
        if args.check:
            require(path.is_file() and path.read_bytes() == body, "figure differs: " + name)
        else:
            path.write_bytes(body)
    print(json.dumps({"matplotlib_backend": "Agg", "figures": {
        name: {"sha256": hashlib.sha256(body).hexdigest(), "bytes": len(body)}
        for name, body in outputs.items()}, "figure_source_sha256": figure_source_sha(coverage, annotations, vocabulary),
        "quantities_summed_or_converted": False}, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
